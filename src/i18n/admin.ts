const dictionaries: Record<AdminLocale, Record<AdminKey, string>> = { en, es };

export type AdminDictionary = Record<AdminKey, string>;
export const adminDictionary = (locale: AdminLocale) => dictionaries[locale];

/** The admin's language: the staff member's last choice, else Spanish unless the browser prefers English. */
export function adminLocale(request: Request): AdminLocale {
  const cookie = request.headers.get('cookie')?.match(/(?:^|;\s*)mz_admin_lang=(en|es)/)?.[1];
  if (cookie === 'en' || cookie === 'es') return cookie;
  return /^en\b/i.test(request.headers.get('accept-language') ?? '') ? 'en' : 'es';
}

export const fillAdmin = (dict: AdminDictionary, key: AdminKey, vars: Record<string, string | number> = {}) =>
  dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
