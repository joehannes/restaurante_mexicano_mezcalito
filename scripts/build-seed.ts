/**
 * Turn seed/data.ts into seed/seed.sql for `wrangler d1 execute`.
 *
 *   node scripts/build-seed.ts
 *
 * The SQL wipes and refills the content tables only (menu, nights, seasons,
 * settings, the radio script). Orders and reservations are never touched.
 */
import { writeFileSync } from 'node:fs';
import { seedRows } from '../seed/rows.ts';

const q = (value: unknown): string => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  const text = typeof value === 'string' ? value : JSON.stringify(value);
  return `'${text.replaceAll("'", "''")}'`;
};

const rows = seedRows();
// Children first when deleting, parents first when inserting.
const order = [
  'categories',
  'modifier_groups',
  'modifier_options',
  'menu_items',
  'item_variants',
  'item_modifier_groups',
  'specials',
  'seasons',
  'settings',
  'radio_nodes',
] as const;

const sql = ['-- Generated by scripts/build-seed.ts from seed/data.ts. Do not edit by hand.'];
for (const table of [...order].reverse()) sql.push(`DELETE FROM ${table};`);
for (const table of order) {
  for (const values of rows[table] as Record<string, unknown>[]) {
    sql.push(`INSERT INTO ${table} (${Object.keys(values).join(', ')}) VALUES (${Object.values(values).map(q).join(', ')});`);
  }
}

writeFileSync(new URL('../seed/seed.sql', import.meta.url), `${sql.join('\n')}\n`);
console.log(`seed/seed.sql: ${sql.length - 1} statements`);
